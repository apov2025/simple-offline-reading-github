#!/usr/bin/env python3
"""把 TeX 的英文断词规则转成固件用的查找表 main/book/hyphen_en_table.h。

Turn the TeX hyphenation patterns for American English into the lookup table the
firmware uses, main/book/hyphen_en_table.h.

表的格式 / Table layout:
  k_hyph_pool   每条规则：字母串、NUL、然后是"字母数 + 1"个数字（0..9 的数值）。
                Each pattern: its letters, a NUL, then (letters + 1) digit values 0..9.
  k_hyph_index  各规则在 pool 里的偏移，按字母串排序，供二分查找。
                Offsets of the patterns in the pool, sorted by letters for binary search.
  k_hyph_exceptions  例外词，连字符标出断点。/ Exception words with their breaks marked by hyphens.

用法 / Usage:  python3 tools/gen_hyphen_table.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATTERNS = ROOT / "tools/hyphen/hyph-en-us.pat.txt"
EXCEPTIONS = ROOT / "tools/hyphen/hyph-en-us.hyp.txt"
OUT = ROOT / "main/book/hyphen_en_table.h"


def parse(pattern: str) -> tuple[str, list[int]]:
    letters, digits = "", [0]
    for ch in pattern:
        if ch.isdigit():
            digits[-1] = int(ch)
        else:
            letters += ch
            digits.append(0)
    return letters, digits


def main() -> None:
    patterns = sorted(parse(line.strip()) for line in PATTERNS.read_text().splitlines() if line.strip())
    assert len({letters for letters, _ in patterns}) == len(patterns), "duplicate pattern letters"
    exceptions = [line.strip() for line in EXCEPTIONS.read_text().splitlines() if line.strip()]

    pool = bytearray()
    index = []
    for letters, digits in patterns:
        assert letters.isascii() and len(digits) == len(letters) + 1
        index.append(len(pool))
        pool += letters.encode() + b"\0" + bytes(digits)
    longest = max(len(letters) for letters, _ in patterns)

    out = [
        "/*",
        " * 由 tools/gen_hyphen_table.py 生成，勿手改。数据来自 TeX hyph-utf8 的美式英语断词规则：",
        " * Generated by tools/gen_hyphen_table.py; do not edit. Data: TeX hyph-utf8 patterns for American English.",
        " *",
        " * Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken",
        " * Copying and distribution of this file, with or without modification,",
        " * are permitted in any medium without royalty provided the copyright",
        " * notice and this notice are preserved.",
        " */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define HYPH_PATTERN_COUNT {len(patterns)}",
        f"#define HYPH_PATTERN_MAX_LETTERS {longest}",
        "",
        "static const uint8_t k_hyph_pool[] = {",
    ]
    for i in range(0, len(pool), 24):
        out.append("    " + ",".join(str(b) for b in pool[i:i + 24]) + ",")
    out += ["};", "", "static const uint32_t k_hyph_index[HYPH_PATTERN_COUNT] = {"]
    for i in range(0, len(index), 16):
        out.append("    " + ",".join(str(v) for v in index[i:i + 16]) + ",")
    out += ["};", "", "static const char* const k_hyph_exceptions[] = {"]
    out += [f'    "{word}",' for word in exceptions]
    out += ["};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(patterns)} patterns, pool {len(pool)} bytes, longest {longest} letters, {len(exceptions)} exceptions")


if __name__ == "__main__":
    main()
